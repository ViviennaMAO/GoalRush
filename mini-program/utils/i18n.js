export const LANG_LABELS = {
  'en': '🇬🇧 English',
  'es': '🇪🇸 Español',
  'pt': '🇧🇷 Português',
  'de': '🇩🇪 Deutsch',
  'fr': '🇫🇷 Français',
  'zh-Hant': '🇭🇰 繁體中文',
};

export const ALL_LANGS = Object.keys(LANG_LABELS);
const STORAGE_KEY = 'goalrush_lang_v2';

function detect() {
  // 1. 已选过 → 用持久化
  try {
    const s = wx.getStorageSync(STORAGE_KEY);
    if (s && STRINGS[s]) return s;
  } catch (e) {}
  // 2. Luffa 系统语言(异步,这里返回默认值,首次启动后异步覆盖)
  try {
    const app = getApp();
    if (app && app.globalData && app.globalData.language) {
      const l = app.globalData.language.toLowerCase();
      if (l.startsWith('zh')) return 'zh-Hant';
      if (l.startsWith('es')) return 'es';
      if (l.startsWith('pt')) return 'pt';
      if (l.startsWith('de')) return 'de';
      if (l.startsWith('fr')) return 'fr';
    }
  } catch (e) {}
  return 'en';
}

export function getLang() {
  return detect();
}

export function setLang(l) {
  if (!STRINGS[l]) return;
  try { wx.setStorageSync(STORAGE_KEY, l); } catch (e) {}
  try {
    const app = getApp();
    if (app && app.globalData) app.globalData.lang = l;
  } catch (e) {}
}

export function t(key, lang) {
  const l = lang || getLang();
  return (STRINGS[l] && STRINGS[l][key]) || (STRINGS.en[key]) || key;
}

// 把扁平字典(点分键)转成下划线键,WXML 友好
// 'nav.home' → 'nav_home'
export function getDict(lang) {
  const l = lang || getLang();
  const src = STRINGS[l] || STRINGS.en;
  const out = {};
  Object.keys(src).forEach(k => {
    out[k.replace(/\./g, '_')] = src[k];
  });
  return out;
}
