function getLang() {
  let l = null;
  try { l = localStorage.getItem(LANG_KEY); } catch (e) {}
  if (l && STRINGS[l]) return l;
  const nav = ((navigator && navigator.language) || 'en').toLowerCase();
  if (nav.startsWith('zh')) return 'zh-Hant';
  if (nav.startsWith('es')) return 'es';
  if (nav.startsWith('pt')) return 'pt';
  if (nav.startsWith('de')) return 'de';
  if (nav.startsWith('fr')) return 'fr';
  return 'en';
}

function setLang(l) {
  if (!STRINGS[l]) return;
  try { localStorage.setItem(LANG_KEY, l); } catch (e) {}
  applyI18n();
  if (typeof trackEvent === 'function') trackEvent('lang_switch', { lang: l });
}

function t(key) {
  const l = getLang();
  return (STRINGS[l] && STRINGS[l][key]) || (STRINGS.en[key]) || key;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    el.innerHTML = t(k);
  });
  const sw = document.getElementById('lang-switch');
  if (sw) sw.textContent = LANG_LABELS[getLang()];
  document.documentElement.lang = getLang();
}

function renderLangSwitcher() {
  return `
    <div class="lang-wrap">
      <button id="lang-switch" class="lang-btn">${LANG_LABELS[getLang()]}</button>
      <div class="lang-menu" id="lang-menu">
        ${Object.keys(LANG_LABELS).map(l => `<button onclick="setLang('${l}');toggleLangMenu()" class="${l===getLang()?'active':''}">${LANG_LABELS[l]}</button>`).join('')}
      </div>
    </div>
  `;
}

function toggleLangMenu() {
  document.getElementById('lang-menu')?.classList.toggle('open');
}

document.addEventListener('click', (e) => {
  if (!e.target.closest('.lang-wrap')) {
    document.getElementById('lang-menu')?.classList.remove('open');
  } else if (e.target.id === 'lang-switch') {
    toggleLangMenu();
  }
});
