const LANG_KEY = 'luffa_lang_v1';

function getLang() {
  let l = localStorage.getItem(LANG_KEY);
  if (l && I18N[l]) return l;
  // 浏览器自动检测
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('zh')) l = 'zh';
  else if (nav.startsWith('es')) l = 'es';
  else if (nav.startsWith('pt')) l = 'pt';
  else l = 'en';
  return l;
}

function setLang(l) {
  if (!I18N[l]) return;
  localStorage.setItem(LANG_KEY, l);
  applyI18n();
  trackEvent && trackEvent('lang_switch', { lang: l });
}

function t(key) {
  const l = getLang();
  return (I18N[l] && I18N[l][key]) || (I18N.en[key]) || key;
}

function applyI18n() {
  // 替换所有 data-i18n 属性
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    el.innerHTML = t(k);
  });
  // 更新 lang switcher 显示
  const sw = document.getElementById('lang-switch');
  if (sw) {
    const labels = { zh: '🇨🇳 中', en: '🇬🇧 EN', es: '🇪🇸 ES', pt: '🇧🇷 PT' };
    sw.textContent = labels[getLang()];
  }
  document.documentElement.lang = getLang();
}

function renderLangSwitcher() {
  const labels = { zh: '🇨🇳 中', en: '🇬🇧 EN', es: '🇪🇸 ES', pt: '🇧🇷 PT' };
  return `
    <div class="lang-wrap">
      <button id="lang-switch" class="lang-btn">${labels[getLang()]}</button>
      <div class="lang-menu" id="lang-menu">
        ${Object.keys(labels).map(l => `<button onclick="setLang('${l}');toggleLangMenu()" class="${l===getLang()?'active':''}">${labels[l]}</button>`).join('')}
      </div>
    </div>
  `;
}

function toggleLangMenu() {
  document.getElementById('lang-menu').classList.toggle('open');
}

// 点外面关菜单
document.addEventListener('click', (e) => {
  if (!e.target.closest('.lang-wrap')) {
    document.getElementById('lang-menu')?.classList.remove('open');
  } else if (e.target.id === 'lang-switch') {
    toggleLangMenu();
  }
});
